from pathlib import Path
from zipfile import ZipFile
from lxml import etree
import re

source=Path('docs/ICD初稿-20261008.docx')
target=Path('docs/AVIATOR故障编码规范.md')
root=etree.fromstring(ZipFile(source).read('word/document.xml'))
ns={'w':'http://schemas.openxmlformats.org/wordprocessingml/2006/main'}
tables=[]
for table in root.findall('.//w:body/w:tbl',ns):
    rows=[]
    for row in table.findall('w:tr',ns):
        rows.append([''.join(cell.xpath('.//w:t/text()',namespaces=ns)) for cell in row.findall('w:tc',ns)])
    tables.append(rows)

def find_table(header,first_code):
    return next(rows for rows in tables if rows[0]==header and rows[1][0]==first_code)

selected=[
('4.1 左右机械臂',find_table(['左臂码','右臂码','故障名称'],'1201')),
('4.2 左右灵巧手',find_table(['左手码','右手码','故障名称'],'3101')),
('4.3 相机与视觉检测',find_table(['故障码','故障名称'],'5101')),
('4.4 应急脱开机构',find_table(['故障码','故障名称'],'6301')),
('4.5 通信与控制输入',find_table(['故障码','故障名称'],'7101')),
('4.6 整机控制',find_table(['故障码','故障名称'],'8001')),
]
codes=[int(c) for _,rows in selected for row in rows[1:] for c in row[:-1]]
assert len(codes)==50 and len(set(codes))==50
assert all(1000<=c<=9999 and 1<=c//1000<=8 and c//100%10<=3 and 1<=c%100<=98 for c in codes)

intro='''# AVIATOR 机器人系统故障编码规范

版本：V1.1 ICD 简化版  
日期：2026-10-09  
依据：[ICD初稿-20261008.docx](ICD初稿-20261008.docx) 第 1 部分上行帧定义及第 3 部分故障编码。

本规范按当前 ICD 整理，保留 **8 个已分配类别、50 个故障码**。故障码占 **2 字节**，按 **无符号 uint16、小端模式**传输，十进制编码范围为 **1000～9999**。具体码值和名称以本文第 4 节与 ICD 对应表为准，替代 V1.0 扩展码表。

本文仅规定故障编码与接口解释，不代表相应检测和上报功能已经实现。当前 ICD 为下行 **9 字节**、上行 **29 字节**、周期 **12.5 ms（80 Hz）**；原规范引用的 14/65 字节、20 ms 帧格式不再适用于本文。

## 1. 编码规则

```text
故障码 = 类别 C × 1000 + 等级 S × 100 + 具体编号 NN
编码形式：CSNN
```

| 段 | 取值 | 含义 |
| --- | --- | --- |
| 千位 C | 1～9 | 类别字段允许范围；当前仅分配 1～8，9 类未分配。 |
| 百位 S | 0～3 | 0 警告；1 自恢复故障；2 需手动恢复故障；3 不可恢复故障。 |
| 后两位 NN | 01～98 | 具体故障；仅第 4 节列出的完整组合可以发送。 |

示例：`1203 = 1×1000 + 2×100 + 03`，表示**左机械臂、需手动恢复、过流保护**。

码值按十进制分配，不是十六进制分段、BCD 或 ASCII。接收后按整数运算拆分：

```text
C  = code / 1000
S  = (code / 100) % 10
NN = code % 100
```

`NN=00`、`NN=99`、等级位 4～9 及未列入码表的组合均不发送。原 V1.0 的 `x099/x199/x299/x399` 通用码和 9 类故障码不再使用；`9999` 也不表示未知故障。未映射的内部错误保留原始诊断，不能临时编造外部码或当作健康。

无故障值暂沿用 `0x0000`，不属于故障码范围；当前 ICD 未单列这一哨兵值，需在接口确认时补充。未知码应保留原值并标记为未识别，不转换成无故障。

## 2. 类别分配

| 千位 | 类别 | 编码区间 | 说明 |
| ---: | --- | --- | --- |
| 1 | 左机械臂 | 1000～1399 | 左机械臂报错信息。 |
| 2 | 右机械臂 | 2000～2399 | 右机械臂报错信息。 |
| 3 | 左灵巧手 | 3000～3399 | 左灵巧手报错信息。 |
| 4 | 右灵巧手 | 4000～4399 | 右灵巧手报错信息。 |
| 5 | 相机 | 5000～5399 | 视觉检测报错信息。 |
| 6 | 应急脱开机构 | 6000～6399 | 快速脱离机构报错信息。 |
| 7 | 通信与控制输入 | 7000～7399 | RS422 主备通道、ZMQ BUS 等报错信息。 |
| 8 | 整机控制 | 8000～8399 | 主控程序报错信息。 |

区间表示类别和等级的分配空间，不代表区间内所有数值都有效。左右机械臂、左右灵巧手使用对称编号；关节号、手指通道和原厂错误信息保留在内部诊断中。

## 3. 等级与故障状态

| 百位 | 等级 | 恢复含义 |
| ---: | --- | --- |
| 0 | 警告 | 提示异常或资源裕量不足。 |
| 1 | 自恢复故障 | 原因消除并确认恢复后，该故障可自动清除。 |
| 2 | 需手动恢复故障 | 原因消除后，仍需人工确认或错误复位。 |
| 3 | 不可恢复故障 | 不能通过普通业务复位继续本次运行，需检修或维护处置。 |

诊断清除不表示自动恢复操控，仍应按机器人状态机执行恢复流程。设备无法连接的条目按 ICD 编入 `x3xx`，不得自行降为自恢复故障。

**ICD 中故障状态字存在两套数值，尚需统一：**

| 含义 | 第 1 部分上行帧字节 21 | 第 3 部分等级映射表 |
| --- | --- | --- |
| 正常 | `0x00` | 未单列 |
| 注意（警告） | `0x10` | `0x01` |
| 提示（自恢复） | `0x20` | `0x02` |
| 告警（手动恢复） | `0x30` | `0x03` |
| 危险（不可恢复） | `0x40` | `0x04` |

故障码百位含义没有冲突；冲突只涉及独立的故障状态字。本文保留两处原值作为待确认项，不指定其中一套为已冻结线上编码。

## 4. 故障码表

以下码值和故障名称逐项取自当前 ICD，不保留旧版额外扩展项。
'''
