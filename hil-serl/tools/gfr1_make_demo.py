#!/usr/bin/env python3
"""Create auditable fixed-duration GFR-1 demonstration transitions.

The demonstrations are generated by the same structured backend used by the
GFR runner.  They are deliberately stored outside all historical N1--N17
artifacts and contain the complete transition fields expected by RLPD.
"""

from __future__ import annotations

import argparse
import copy
import json
import pickle
from pathlib import Path

import numpy as np

from examples.experiments.aviator_manifold.gfr_env import GFRManifoldEnv


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--manifold", required=True)
    p.add_argument("--model", required=True)
    p.add_argument("--trajectory-dir", required=True)
    p.add_argument("--split", default="rl_train")
    p.add_argument("--episodes", type=int, default=8)
    p.add_argument("--output", required=True)
    p.add_argument("--manifest", required=True)
    p.add_argument("--seed", type=int, default=20261011)
    p.add_argument("--mode", choices=("raw", "structured", "fixed"), default="structured")
    p.add_argument("--visible-error", action=argparse.BooleanOptionalAction, default=True)
    args = p.parse_args()

    env = GFRManifoldEnv(
        manifold_dir=args.manifold,
        model_path=args.model,
        trajectory_dir=args.trajectory_dir,
        split=args.split,
        mode=args.mode,
        visible_error=args.visible_error,
        dt=0.005,
        d_safe=0.005,
        beta_stop=0.125,
    )
    transitions = []
    episodes = []
    for ep in range(args.episodes):
        obs, _ = env.reset(seed=args.seed + ep, options={"trajectory_index": ep})
        episode_start = len(transitions)
        done = truncated = False
        steps = 0
        while not (done or truncated):
            action = np.zeros(2, dtype=np.float32)
            next_obs, reward, done, truncated, info = env.step(action)
            terminal = bool(done or truncated)
            transitions.append({
                "observations": copy.deepcopy(obs),
                "actions": action.copy(),
                "next_observations": copy.deepcopy(next_obs),
                "rewards": np.asarray(reward, dtype=np.float32),
                "masks": np.asarray(1.0 - terminal, dtype=np.float32),
                "dones": np.asarray(terminal, dtype=bool),
            })
            obs = next_obs
            steps += 1
            if steps > 2000:
                raise RuntimeError("demo episode exceeded 2000 steps")
        episodes.append({
            "episode": ep,
            "transition_start": episode_start,
            "transition_count": len(transitions) - episode_start,
            "termination": info.get("termination"),
            "progress": float(info.get("progress", np.nan)),
            "min_clearance_m": float(info.get("d_actual_m", np.nan)),
        })

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("wb") as f:
        pickle.dump(transitions, f)
    manifest = {
        "kind": "gfr1_demo_manifest",
        "mode": args.mode,
        "visible_error": args.visible_error,
        "split": args.split,
        "episodes": episodes,
        "transition_count": len(transitions),
        "output": str(out),
        "frozen": {"dt": 0.005, "d_safe": 0.005, "beta_stop": 0.125},
    }
    m = Path(args.manifest)
    m.parent.mkdir(parents=True, exist_ok=True)
    m.write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({"transition_count": len(transitions), "episodes": episodes}, indent=2))


if __name__ == "__main__":
    main()
