#!/usr/bin/env python3
"""Convert complete online-governor traces into GFR RLPD demonstrations.

The source traces are generated by the non-RL online endpoint governor.  Only
complete trials with accepted endpoint/swept checks are admitted.  This keeps
successful demonstrations separate from exploratory failures.
"""

from __future__ import annotations

import argparse
import copy
import json
import pickle
from pathlib import Path

import numpy as np

from examples.experiments.aviator_manifold.manifold_lookup import ManifoldLookup
from tools.audit_static_collision import CollisionChecker
from tools.validate_differential_lift import AviatorClosure
from tools.validate_online_lift import analytic_constraint_matrices


def state(fk, checker, lookup, x, q, xdot, sigma, r_prev, beta_prev,
          intervention, rejection, recovery, progress, visible_error):
    e = np.asarray(fk.error(x, q), dtype=np.float64)
    d, _ = checker.check(x, q)
    lower = np.concatenate([lookup.joint_lower[0], lookup.joint_lower[1]])
    upper = np.concatenate([lookup.joint_upper[0], lookup.joint_upper[1]])
    qmargin = min(float(np.min(q - lower)), float(np.min(upper - q)))
    e_obs = e if visible_error else np.zeros(12, dtype=np.float64)
    return np.r_[x, xdot, q, e_obs, float(d), qmargin, float(sigma),
                 r_prev, float(beta_prev), float(intervention),
                 float(rejection), float(recovery), float(progress)].astype(np.float32)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--raw", nargs="+", required=True)
    p.add_argument("--manifold", required=True)
    p.add_argument("--output", required=True)
    p.add_argument("--manifest", required=True)
    p.add_argument("--visible-error", action=argparse.BooleanOptionalAction, default=True)
    p.add_argument("--max-episodes", type=int, default=100)
    args = p.parse_args()
    lookup = ManifoldLookup(args.manifold)
    trials = []
    for raw_path in args.raw:
        d = json.loads(Path(raw_path).read_text())
        trials.extend(d["trial_rows"])
    trials = [r for r in trials if r.get("method") == "online_endpoint_governor"
              and bool(r.get("complete"))]
    trials.sort(key=lambda r: (r.get("family", ""), float(r.get("error_level", 0)),
                               int(r.get("trial", 0)), r.get("speed", "")))
    trials = trials[:args.max_episodes]
    if len(trials) < args.max_episodes:
        raise RuntimeError(f"need {args.max_episodes} complete trials, found {len(trials)}")

    transitions, episodes = [], []
    for ep, trial in enumerate(trials):
        model = trial["model"]
        fk, checker = AviatorClosure(model), CollisionChecker(model)
        traces = trial["step_trace"]
        prev_r = np.zeros(2, dtype=np.float64)
        prev_beta = 1.0
        prev_intervention = prev_rejection = prev_recovery = 0.0
        start = len(transitions)
        for i, tr in enumerate(traces):
            if not tr.get("accepted") or not tr.get("endpoint_pass") or not tr.get("swept_pass"):
                raise RuntimeError(f"non-accepted trace in complete trial {ep} step {i}")
            x0 = np.asarray(tr["x_before"], dtype=np.float64)
            q0 = np.asarray(tr["q_before"], dtype=np.float64)
            x1 = np.asarray(tr["x_after"], dtype=np.float64)
            q1 = np.asarray(tr["q_after"], dtype=np.float64)
            xdot = np.asarray(tr["xdot_nom"], dtype=np.float64)
            beta = float(tr["beta"])
            r_exec = np.asarray(tr["r_exec"], dtype=np.float64)
            intervention = float(tr["task_scale"] < 1.0 - 1e-10 or
                                 tr["phase_scale"] < 1.0 - 1e-10 or beta < 1.0 - 1e-10)
            rejection = float(tr.get("governor_attempt_count", 1) > 1 or
                              np.linalg.norm(r_exec - np.asarray(tr["r_nom"], dtype=float)) > 1e-8)
            progress0, progress1 = float(tr["task_progress_before"]), float(tr["task_progress_after"])
            obs0 = state(fk, checker, lookup, x0, q0, xdot, float(tr["sigma_min_Aq"]),
                         prev_r, prev_beta, prev_intervention, prev_rejection,
                         prev_recovery, progress0, args.visible_error)
            obs1 = state(fk, checker, lookup, x1, q1, xdot, float(tr["sigma_min_Aq"]),
                         r_exec, beta, intervention, rejection, 0.0,
                         progress1, args.visible_error)
            if obs0.shape != (40,) or obs1.shape != (40,):
                raise RuntimeError("GFR observation shape mismatch")
            terminal = bool(i == len(traces) - 1)
            reward = (10.0 * (progress1 - progress0)
                      - 0.02 * intervention
                      - 0.001 * float(tr.get("governor_attempt_count", 1))
                      + (100.0 if terminal else 0.0))
            transitions.append({
                "observations": {"state": obs0},
                "actions": np.clip(r_exec / 1.5, -1.0, 1.0).astype(np.float32),
                "next_observations": {"state": obs1},
                "rewards": np.asarray(reward, dtype=np.float32),
                "masks": np.asarray(1.0 - terminal, dtype=np.float32),
                "dones": np.asarray(terminal, dtype=bool),
            })
            prev_r, prev_beta = r_exec, beta
            prev_intervention, prev_rejection, prev_recovery = intervention, rejection, 0.0
        episodes.append({
            "episode": ep, "source_family": trial.get("family"),
            "source_error_level": trial.get("error_level"), "source_speed": trial.get("speed"),
            "source_trial": trial.get("trial"), "transition_start": start,
            "transition_count": len(transitions) - start, "termination": "end",
            "source_progress": float(trial["task_progress_fraction"]),
        })
    out = Path(args.output); out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("wb") as f: pickle.dump(transitions, f)
    manifest = {
        "kind": "gfr1_success_demo_manifest", "visible_error": args.visible_error,
        "episodes": episodes, "transition_count": len(transitions),
        "source_raw": [str(Path(x).resolve()) for x in args.raw],
        "frozen": {"dt": 0.005, "d_safe": 0.005, "beta_stop": 0.125,
                   "source_method": "online_endpoint_governor"},
    }
    Path(args.manifest).write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({"episodes": len(episodes), "transitions": len(transitions),
                      "all_complete": True}, indent=2))


if __name__ == "__main__":
    main()
